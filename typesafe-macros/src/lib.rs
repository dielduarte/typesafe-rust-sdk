//! Derive macros for the TypeSafe Rust SDK. Use them through the `typesafe` crate.

use proc_macro::TokenStream;
use proc_macro2::{Span, TokenStream as TokenStream2};
use quote::{format_ident, quote};
use syn::{Data, DeriveInput, Fields, Ident, LitStr, parse_macro_input};

/// Derive `typesafe::QuestionSet` and a `<Name>Answers` struct.
#[proc_macro_derive(QuestionSet, attributes(question))]
pub fn derive_question_set(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    question_set(&input).unwrap_or_else(syn::Error::into_compile_error).into()
}

/// Derive `typesafe::Choices` for a fieldless enum.
#[proc_macro_derive(Choices, attributes(choice))]
pub fn derive_choices(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    choices(&input).unwrap_or_else(syn::Error::into_compile_error).into()
}

fn question_set(input: &DeriveInput) -> syn::Result<TokenStream2> {
    reject_generics(input, "QuestionSet")?;
    let Data::Struct(data) = &input.data else {
        return Err(syn::Error::new_spanned(&input.ident, "QuestionSet can only be derived for structs"));
    };
    let Fields::Named(fields) = &data.fields else {
        return Err(syn::Error::new_spanned(&input.ident, "QuestionSet needs a struct with named fields"));
    };
    if fields.named.is_empty() {
        return Err(syn::Error::new_spanned(&input.ident, "QuestionSet needs at least one question"));
    }

    let name = &input.ident;
    let vis = &input.vis;
    let answers = format_ident!("{}Answers", name);
    let answers_doc = format!("Answers to [`{name}`], generated by `#[derive(QuestionSet)]`.");

    let mut wire_names = Vec::new();
    let mut idents = Vec::new();
    let mut types = Vec::new();
    for field in &fields.named {
        let ident = field.ident.as_ref().expect("named fields have identifiers");
        let mut wire = LitStr::new(&unraw(ident), ident.span());
        for attr in field.attrs.iter().filter(|a| a.path().is_ident("question")) {
            attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("rename") {
                    wire = meta.value()?.parse()?;
                    Ok(())
                } else {
                    Err(meta.error("expected `rename = \"...\"`"))
                }
            })?;
        }
        if let Some(previous) = wire_names.iter().find(|w: &&LitStr| w.value() == wire.value()) {
            let mut err = syn::Error::new(wire.span(), format!("duplicate question name {:?}", wire.value()));
            err.combine(syn::Error::new(previous.span(), "first used here"));
            return Err(err);
        }
        wire_names.push(wire);
        idents.push(ident);
        types.push(&field.ty);
    }
    let field_docs = wire_names.iter().map(|w| format!("Answer to the `{}` question.", w.value()));

    Ok(quote! {
        #[doc = #answers_doc]
        #[derive(::core::fmt::Debug, ::core::clone::Clone, ::core::cmp::PartialEq, ::typesafe::__private::serde::Deserialize)]
        #[serde(crate = "::typesafe::__private::serde")]
        #vis struct #answers {
            #(
                #[doc = #field_docs]
                #[serde(rename = #wire_names)]
                pub #idents: <#types as ::typesafe::TypedQuestion>::Answer,
            )*
        }

        #( const _: () = <#types as ::typesafe::TypedQuestion>::CHECK; )*

        impl ::typesafe::QuestionSet for #name {
            type Answers = #answers;

            fn into_questions(self) -> ::typesafe::Questions {
                let mut questions = ::typesafe::Questions::new();
                #(
                    questions.insert(#wire_names, ::typesafe::TypedQuestion::into_question(self.#idents));
                )*
                questions
            }
        }
    })
}

fn choices(input: &DeriveInput) -> syn::Result<TokenStream2> {
    reject_generics(input, "Choices")?;
    let Data::Enum(data) = &input.data else {
        return Err(syn::Error::new_spanned(&input.ident, "Choices can only be derived for enums"));
    };
    if data.variants.is_empty() {
        return Err(syn::Error::new_spanned(&input.ident, "Choices needs at least one variant"));
    }

    let mut labels: Vec<LitStr> = Vec::new();
    let mut variants = Vec::new();
    for variant in &data.variants {
        if !matches!(variant.fields, Fields::Unit) {
            return Err(syn::Error::new_spanned(variant, "Choices variants can't have fields"));
        }
        let mut label = LitStr::new(&snake_case(&unraw(&variant.ident)), variant.ident.span());
        for attr in variant.attrs.iter().filter(|a| a.path().is_ident("choice")) {
            attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("label") {
                    label = meta.value()?.parse()?;
                    Ok(())
                } else {
                    Err(meta.error("expected `label = \"...\"`"))
                }
            })?;
        }
        if labels.iter().any(|l| l.value() == label.value()) {
            return Err(syn::Error::new(label.span(), format!("duplicate choice label {:?}", label.value())));
        }
        labels.push(label);
        variants.push(&variant.ident);
    }

    let name = &input.ident;
    let indices = (0..variants.len()).map(|i| syn::LitInt::new(&i.to_string(), Span::call_site()));
    let indices2 = indices.clone();
    Ok(quote! {
        impl ::typesafe::Choices for #name {
            const LABELS: &'static [&'static str] = &[#(#labels),*];

            fn index(self) -> usize {
                match self {
                    #( Self::#variants => #indices, )*
                }
            }

            fn from_index(index: usize) -> ::core::option::Option<Self> {
                match index {
                    #( #indices2 => ::core::option::Option::Some(Self::#variants), )*
                    _ => ::core::option::Option::None,
                }
            }
        }
    })
}

fn reject_generics(input: &DeriveInput, derive: &str) -> syn::Result<()> {
    if input.generics.params.is_empty() {
        Ok(())
    } else {
        Err(syn::Error::new_spanned(&input.generics, format!("{derive} can't be derived for generic types")))
    }
}

fn unraw(ident: &Ident) -> String {
    let s = ident.to_string();
    s.strip_prefix("r#").map(str::to_owned).unwrap_or(s)
}

/// `HTTPError` → `http_error`, `PaidV2` → `paid_v2`, `Calm` → `calm`.
fn snake_case(name: &str) -> String {
    let chars: Vec<char> = name.chars().collect();
    let mut out = String::with_capacity(name.len() + 4);
    for (i, &c) in chars.iter().enumerate() {
        if c.is_uppercase() {
            let prev = i.checked_sub(1).map(|p| chars[p]);
            let next = chars.get(i + 1);
            let after_lower = prev.is_some_and(|p| p.is_lowercase() || p.is_ascii_digit());
            let acronym_end = prev.is_some_and(char::is_uppercase) && next.is_some_and(|n| n.is_lowercase());
            if after_lower || acronym_end {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::snake_case;

    #[test]
    fn converts_variant_names_to_snake_case() {
        assert_eq!(snake_case("Calm"), "calm");
        assert_eq!(snake_case("VeryAngry"), "very_angry");
        assert_eq!(snake_case("HTTPError"), "http_error");
        assert_eq!(snake_case("PaidV2"), "paid_v2");
        assert_eq!(snake_case("already_snake"), "already_snake");
    }
}
